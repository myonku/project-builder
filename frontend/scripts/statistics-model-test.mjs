// Node 24 native TypeScript stripping; no new test dependencies.
import assert from 'node:assert/strict';
import { performance } from 'node:perf_hooks';
import * as m from '../src/components/statistics/statisticsModel.ts';
let checks = 0;
const eq = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const today = '2026-11-04';
const member = id => ({ user_id: id, display_name: id, username: id, role: 'member' });
const task = (id, extra = {}) => ({ id, project_id: 'p', has_children: false, status: 'not_started',
  progress: 0, end_date: today, is_overdue: false, members: [], ...extra });
const parent = task('a', { has_children: true });
const child = task('b', { members: [member('x'), member('y'), member('x')] });
const cancelled = task('c', { status: 'cancelled', end_date: '2020-01-01' });
const all = [parent, child, cancelled, child];
eq(m.leafTasks(all).map(t => t.id), ['b', 'c']);
eq(m.taskMetrics(m.leafTasks(all)), { total: 2, status: { not_started: 1, in_progress: 0, completed: 0, cancelled: 1 }, overdue: 0, open: 1, completion: 0 });
eq(m.taskMetrics([cancelled]).completion, null);
eq(m.taskMetrics([]).completion, null);
eq(m.taskMetrics([task('odd', { status: 'completed', progress: 10 })]).status.completed, 1);
eq(m.taskMetrics([task('odd', { status: 'in_progress', progress: 100 })]).open, 1);
const rows = m.memberDistribution(m.leafTasks(all), m.leafTasks(all));
eq(rows.map(row => [row.member.user_id, row.tasks.length]), [['x', 1], ['y', 1]]);
eq(m.memberDistribution([child], []).map(row => row.tasks.length), [0, 0]);
const projects = [{ id: 'p', progress: 71 }, { id: 'empty', progress: 25 }];
let scope = m.statisticsScope(projects, all, '', '', '');
eq(scope.projects.map(p => p.id), ['p', 'empty']);
eq(scope.tasks.length, 2);
scope = m.statisticsScope(projects, all, '', today, today);
eq(scope.tasks.map(t => t.id), ['b']);
eq(scope.projects, [projects[0]]);
eq(scope.projects[0].progress, 71);
eq(m.statisticsScope(projects, all, 'unavailable', '', '').tasks, []);
eq(m.statisticsScope(projects, [parent], '', '', '').tasks, []);
const dates = ['2026-11-03', today, '2026-11-11', '2026-11-12', '2026-12-04', '2026-12-05'];
const datesTasks = dates.map((date, i) => task(String(i), { end_date: date, is_overdue: i === 0 }));
eq(datesTasks.map(t => m.dueBucket(t, today)), [0, 1, 2, 3, 3, 4]);
eq(m.dueBucket(cancelled, today), null);
eq(m.dueBucket(task('done', { status: 'completed' }), today), null);
eq(m.dueBucket(task('mismatch', { end_date: '2020-01-01' }), today), null);
eq(m.dayDistance('2028-03-01', '2028-02-28'), 2);
eq(m.selectedTasks(datesTasks, { kind: 'due', value: 3 }, today).map(t => t.id), ['3', '4']);
eq(m.selectedTasks([child, cancelled], { kind: 'status', value: 'cancelled' }, today).map(t => t.id), ['c']);
eq(m.selectedTasks([child], null, today).length, 1);
for (const [date, valid] of [['2028-02-29', true], ['2026-02-29', false], ['2026-13-01', false], ['11/04/2026', false], ['', false], ['2026-11-04', true]]) eq(m.validDate(date), valid);
eq(m.isUUID('0199f0c2-8b1e-7a3c-9d2f-5e6a7b8c9d20'), true);
eq(m.isUUID('x'), false);
const report = m.reportText('工作组甲 · 只读共享 · Asia/Shanghai', datesTasks, 1, '2026-11-04 10:00', today, 'http://localhost');
eq(report.includes('叶子任务 6'), true);
eq(report.includes('逾期 1'), true);
eq(report.includes('另有 1 条'), true);
eq(report.includes('http://localhost/projects/p?taskId='), true);
eq(report.includes('不是历史完成期间'), true);
// Representative aggregation benchmark: 1,000 tasks, 100 members, 10 projects.
const large = Array.from({ length: 1000 }, (_, i) => task(String(i), { project_id: `p${i % 10}`,
  members: [member(`u${i % 100}`), member(`u${(i + 1) % 100}`)] }));
const ps = Array.from({ length: 10 }, (_, i) => ({ id: `p${i}`, progress: 50 }));
const start = performance.now();
const big = m.statisticsScope(ps, large, '', '', '');
const dist = m.memberDistribution(big.leaves, big.tasks);
const duration = performance.now() - start;
eq(big.tasks.length, 1000); eq(dist.length, 100); eq(dist.reduce((n, row) => n + row.tasks.length, 0), 2000);
console.log(JSON.stringify({ checks, benchmark: { tasks: 1000, members: 100, aggregationMs: +duration.toFixed(2) } }));
